export function generateTimeSeriesData(points: number = 24): Array<{ timestamp: string; value: number }> {
  const data = [];
  const now = new Date();
  for (let i = points - 1; i >= 0; i--) {
    const timestamp = new Date(now.getTime() - i * 3600000);
    data.push({
      timestamp: timestamp.toISOString(),
      value: 20 + Math.random() * 10 + Math.sin(i / 4) * 3,
    });
  }
  return data;
}

export function generateGaugeValue(min: number = 0, max: number = 100): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}
